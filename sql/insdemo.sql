CREATE OR REPLACE TABLE INSDEMO.POLIZAS (
  NUMPOL   CHAR(10)      NOT NULL PRIMARY KEY,
  TITULAR  VARCHAR(40)   NOT NULL,
  RAMO     CHAR(10)      NOT NULL,
  PRIMA    DECIMAL(9, 2) NOT NULL,
  FECVTO   DATE          NOT NULL,
  ESTADO   CHAR(8)       NOT NULL       -- VIGENTE | IMPAGO | ANULADA
) RCDFMT POLIZASR;

CREATE OR REPLACE TABLE INSDEMO.SINIESTROS (
  IDSIN    INTEGER       GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  NUMPOL   CHAR(10)      NOT NULL,
  FECHA    TIMESTAMP     NOT NULL DEFAULT CURRENT TIMESTAMP,
  IMPORTE  DECIMAL(11, 2) NOT NULL,
  DESCRIP  VARCHAR(50)   NOT NULL,
  ESTADO   CHAR(10)      NOT NULL,      -- ACEPTADO | REVISION | RECHAZADO
  TRACEID  CHAR(32)                     -- Instana trace that registered the claim
) RCDFMT SINIESTR;

DELETE FROM INSDEMO.SINIESTROS;
DELETE FROM INSDEMO.POLIZAS;

